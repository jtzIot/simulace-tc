const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const app=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).find(s=>s.includes('let rawWeather'));
const run=new Function('window','document',app+'\nreturn code=>eval(code);')({addEventListener(){}},{});
const near=(a,b,label)=>assert(Math.abs(a-b)<1e-8,label+': '+a+' != '+b);
assert.equal(run('defaultEnergyConfig().tariff'),'D25d');
run('state.energy=defaultEnergyConfig();state.energy.household={enabled:true,vt:2000,nt:1000,appliances:"Pračka, lednice"}');
let c=run('householdEconomy(state.energy)');
near(c.annualHp,2000*6.32843+1000*3.50394,'VT/NT independent invoice');
near(c.annualGas,3000*5.99805,'gas household uses reference D02d');
near(c.annualSaving,c.annualGas-c.annualHp,'saving sign');
near(run('householdEconomy(state.energy,.6).saving'),(c.annualGas-c.annualHp)*.6,'seasonal estimate');
run('state.energy.household.enabled=false');near(run('householdEconomy().saving'),0,'disabled');
run('state.energy.household.enabled=true;state.energy.household.vt=0;state.energy.household.nt=0');near(run('householdEconomy().saving'),0,'zero consumption');
run('state.energy={...state.energy,tariff:"D02d",...energyTariffs.D02d};state.energy.household={enabled:true,vt:1000,nt:2000,appliances:"Dům"}');
near(run('householdEconomy().saving'),0,'same tariff gives zero saving');
near(run('householdEconomy().ntKwh'),0,'single tariff bills every kWh in VT');
run('state.energy=defaultEnergyConfig();state.energy.household={enabled:true,vt:3000,nt:0,appliances:"Dům"}');
assert(run('householdEconomy().saving')<0,'VT-only can increase cost');
const h=run('householdEconomy().annualHp');run('state.energy.breakerFixed=999;state.energy.existingConnection=false');
near(run('householdEconomy().annualHp'),h,'breaker is not counted twice');
assert.throws(()=>run('validateHouseholdConfig({enabled:true,vt:-1,nt:1,appliances:""})'));
assert.throws(()=>run('validateHouseholdConfig({enabled:true,vt:Infinity,nt:1,appliances:""})'));
assert.throws(()=>run('validateHouseholdConfig({enabled:true,vt:900000,nt:900000,appliances:""})'));
const legacy=run('defaultEnergyConfig()');delete legacy.household;
assert.equal(run('validateEnergyConfig('+JSON.stringify(legacy)+').household.enabled'),false,'old scenarios remain supported');
assert.equal(run('nfmt(1.234567,5)'),'1,23','display precision capped');
assert(run('householdEconomy().annualHp')%1!==0,'calculation precision remains');
console.log('PASS: household VT/NT, baseline tariff, seasonal factor, zero/disabled/same tariff, negative saving, no fixed-charge duplication, validation and legacy scenarios.');
const profileConfig=run('defaultEnergyConfig()');
profileConfig.household={enabled:true,mode:'profiles',vt:0,nt:0,appliances:'',profiles:[{type:'cold',kwh:1200}]};
run('state.energy='+JSON.stringify(profileConfig));
near(run('householdSplit().nt'),400,'continuous fridge D25d has 8/24 NT');
near(run('householdSplit().vt'),800,'continuous fridge D25d VT');
run('state.energy={...state.energy,tariff:"D57d",...energyTariffs.D57d};');
near(run('householdSplit().nt'),1000,'continuous fridge D57d has 20/24 NT');
near(run('householdEconomy().annualKwh'),1200,'annual consumption preserved across tariffs');
run('state.energy.tariff="D25d";state.energy.household.profiles=[{type:"washer",kwh:1200}];state.energy.ntWindows=[[550,1030]];');
near(run('householdSplit().nt'),1100,'10-minute overlap with appliance profile');
run('state.energy.ntWindows=[[0,360],[780,900]]');near(run('householdSplit().nt'),0,'washer outside default D25d NT');
run('state.energy.tariff="D02d";delete state.energy.ntWindows');near(run('householdSplit().nt'),0,'single tariff with profiles');
run('state.energy.household.profiles=[{type:"cold",kwh:400},{type:"washer",kwh:300}];state.energy.tariff="D25d"');
near(run('householdSplit().total'),700,'mixed profiles conserve energy');
near(run('householdSplit().vt+householdSplit().nt'),700,'VT+NT equals annual consumption');
assert.throws(()=>run('validateHouseholdConfig({...defaultHouseholdConfig(),mode:"other"})'));
assert.throws(()=>run('validateHouseholdConfig({...defaultHouseholdConfig(),profiles:[{type:"unknown",kwh:100}]})'));
assert.throws(()=>run('validateHouseholdConfig({...defaultHouseholdConfig(),profiles:[{type:"cold",kwh:-1}]})'));
assert(run('householdApplianceNames()').includes('Lednice'));
console.log('PASS: appliance profiles, continuous-load 8/24 vs 20/24, 10-minute HDO overlaps, annual energy conservation, mixed/zero/single-tariff profiles and validation.');
