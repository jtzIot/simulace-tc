const fs=require('fs'),assert=require('node:assert/strict'),path=require('path');
const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const app=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).find(s=>s.includes('let rawWeather'));
const run=new Function('window','document',app+'\nreturn code=>eval(code);')({addEventListener(){}},{});
const near=(a,b,label)=>assert(Math.abs(a-b)<1e-8,label+': '+a+' != '+b);
assert.equal(run('state.activeHp.certNo'),'011-1W1325');
near(run('getCopForActiveModel(12,24,90,2.35)'),8.95,'exact LT +12 point, no double defrost');
near(run('getCopForActiveModel(12,30,90,2.23)'),6.64,'exact MT +12 point');
near(run('getCopForActiveModel(7,35,80,7.02)'),4.71,'EN14511 A7W35 full output');
near(run('getCopForActiveModel(7,55,80,6.55)'),3.02,'EN14511 A7W55 full output');
near(run('getCapForActiveModel(-11,35)'),0,'below TOL');
near(run('getCapForActiveModel(5,76)'),0,'above WTOL');
near(run('getCapForActiveModel(12,35)'),7.02,'part-load heat is not maximum capacity');
near(run('kmAt(state.activeHp.km.lt,4.5).cop'),((3.06+2.07)/2)/((3.06/4.4+2.07/6.41)/2),'interpolate heat and electricity');
near(run('kmIdlePower(true)'),.01,'Poff watts to kW');near(run('kmIdlePower(false)'),.01,'PSB watts to kW');
run('state.activeHp={...state.activeHp,km:kmClone(state.activeHp.km)};state.activeHp.km.useCycling=true');
assert(run('getCopForActiveModel(12,24,60,1)')<8.95,'optional degradation at lower load');
run('state.activeHp.km.useCycling=false');
near(run('getCopForActiveModel(12,24,60,1)'),8.95,'default no extra degradation');
assert.throws(()=>run('validateKeymarkConfig({...state.activeHp.km,externalPumpW:-1})'));
assert.throws(()=>run('validateKeymarkConfig({...state.activeHp.km,lt:{...state.activeHp.km.lt,tol:0}})'));
run('state.energy=defaultEnergyConfig();Object.assign(state.energy,energyTariffs.D02d,{tariff:"D02d"});state.control=defaultControl();state.qLossDesign=14;state.dhwEnabled=true');
const cold=run('simulateController({t:Array(24).fill(-12),rh:Array(24).fill(80),sol:Array(24).fill(0)},"optimized")');
assert(cold.backup>0,'resistance heater operates under cold conditions');
assert(cold.hours.every(h=>!h.isRunning&&Math.abs(h.q_hp-h.backup)<1e-9),'compressor cannot operate below TOL');
assert(cold.hours.every(h=>h.backup+h.dhwBackup<=3+1e-9),'shared 3 kW heater limit');
near(cold.balanceError,0,'cold energy balance');
run('state.activeHp.km.useStandby=false');near(run('kmIdlePower(false)'),0,'standby opt-out');
console.log('PASS: Keymark 011-1W1325 source knots, full vs part load, capacity estimate, TOL/WTOL, power interpolation, auxiliary watts, degradation option, validation and shared heater energy balance.');
